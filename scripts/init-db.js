/** Валидный ISBN-13 для демонстрационных данных (префикс 978-5). */
function demoIsbn(n) {
  const digits = `9785${String(1000000 + n * 7919).slice(-8)}`;
  const sum = [...digits].reduce((acc, d, i) => acc + Number(d) * (i % 2 ? 3 : 1), 0);
  const check = (10 - (sum % 10)) % 10;
  return `${digits.slice(0, 3)}-${digits.slice(3, 4)}-${digits.slice(4, 8)}-${digits.slice(8)}-${check}`;
}

function monthsAgo(months, n) {
  const d = new Date();
  d.setUTCMonth(d.getUTCMonth() - months, Math.min(28, 3 + (n * 5) % 25));
  return d > new Date() ? new Date() : d;
}

async function run() {
  if (!/^[A-Za-z0-9_]+$/.test(DB_NAME)) throw new Error('DB_NAME может содержать только латиницу, цифры и «_»');

  const master = await new sql.ConnectionPool(buildConfig('master')).connect();
  await master.request().query(`IF DB_ID(N'${DB_NAME}') IS NULL CREATE DATABASE [${DB_NAME}]`);
  await master.close();
  console.log(`База данных ${DB_NAME} готова`);

  const pool = await new sql.ConnectionPool(buildConfig(DB_NAME)).connect();
  try {
    const exists = await pool.request().query("SELECT OBJECT_ID('dbo.Users', 'U') AS id");
    if (exists.recordset[0].id && !RESET) {
      console.log('Таблицы уже существуют. Для пересоздания с демо-данными выполните `npm run db:reset`.');
      return;
    }

    const schema = fs.readFileSync(path.join(__dirname, '..', 'db', 'schema.sql'), 'utf8');
    for (const batch of schema.split(/^\s*GO\s*$/im).map((b) => b.trim()).filter(Boolean)) {
      await pool.request().query(batch);
    }
    console.log('Таблицы созданы');

    await seed(pool);
    console.log('Демо-данные загружены');
    console.log('Учётные записи: admin / admin123 (администратор), reader / reader123 (читатель)');
  } finally {
    await pool.close();
  }
}

async function insert(pool, text, params) {
  const req = pool.request();
  for (const [k, v] of Object.entries(params)) req.input(k, v);
  const r = await req.query(text);
  return r.recordset?.[0]?.id;
}

async function seed(pool) {
  const ids = { genres: {}, authors: {}, books: {}, users: {} };

  for (const [name, description] of GENRES) {
    ids.genres[name] = await insert(pool,
      'INSERT INTO dbo.Genres (Name, Description) OUTPUT INSERTED.Id AS id VALUES (@name, @description)',
      { name, description });
  }

  for (const [name, birthYear, deathYear, country, bio] of AUTHORS) {
    ids.authors[name] = await insert(pool,
      `INSERT INTO dbo.Authors (Name, BirthYear, DeathYear, Country, Bio) OUTPUT INSERTED.Id AS id
       VALUES (@name, @birthYear, @deathYear, @country, @bio)`,
      { name, birthYear, deathYear, country, bio });
  }

  for (const [i, [title, author, genre, year, publisher, language, pages, annotation, ago]] of BOOKS.entries()) {
    ids.books[title] = await insert(pool,
      `INSERT INTO dbo.Books (Title, AuthorId, GenreId, Year, ISBN, Publisher, Language, Pages, Annotation, CreatedAt)
       OUTPUT INSERTED.Id AS id
       VALUES (@title, @authorId, @genreId, @year, @isbn, @publisher, @language, @pages, @annotation, @createdAt)`,
      { title, authorId: ids.authors[author], genreId: ids.genres[genre], year, isbn: demoIsbn(i + 1),
        publisher, language, pages, annotation, createdAt: monthsAgo(ago, i) });
  }

  for (const [username, email, password, displayName, role] of USERS) {
    ids.users[username] = await insert(pool,
      `INSERT INTO dbo.Users (Username, Email, PasswordHash, DisplayName, Role) OUTPUT INSERTED.Id AS id
       VALUES (@username, @email, @passwordHash, @displayName, @role)`,
      { username, email, passwordHash: await bcrypt.hash(password, 10), displayName, role });
  }

  for (const [user, book, rating, text] of REVIEWS) {
    await insert(pool,
      'INSERT INTO dbo.Reviews (UserId, BookId, Rating, Text) VALUES (@userId, @bookId, @rating, @text)',
      { userId: ids.users[user], bookId: ids.books[book], rating, text });
  }

  for (const [user, book, status, currentPage] of SHELF) {
    await insert(pool,
      'INSERT INTO dbo.Shelf (UserId, BookId, Status, CurrentPage) VALUES (@userId, @bookId, @status, @currentPage)',
      { userId: ids.users[user], bookId: ids.books[book], status, currentPage });
  }

  await insert(pool,
    `INSERT INTO dbo.BookRequests (UserId, Title, AuthorName, Comment) VALUES
       (@reader, N'Гарри Поттер и философский камень', N'Джоан Роулинг', N'Очень хотелось бы видеть в каталоге!'),
       (@anna, N'Мы', N'Евгений Замятин', N'Классическая антиутопия, предшественница «1984».')`,
    { reader: ids.users.reader, anna: ids.users.anna });
  await insert(pool,
    `INSERT INTO dbo.BookRequests (UserId, Title, AuthorName, Comment, Status, AdminComment, ReviewedAt)
     VALUES (@ivan, N'Моя книга', N'Иван', N'Хочу добавить свою рукопись', N'rejected',
             N'В каталог добавляются только изданные книги', SYSUTCDATETIME())`,
    { ivan: ids.users.ivan });

  for (const [title, body, daysAgo] of NEWS) {
    await insert(pool,
      'INSERT INTO dbo.News (Title, Body, AuthorId, CreatedAt) VALUES (@title, @body, @authorId, @createdAt)',
      { title, body, authorId: ids.users.admin, createdAt: new Date(Date.now() - daysAgo * 86400000) });
  }
}

run().catch((err) => {
  console.error('Ошибка инициализации базы данных:', err.message);
  process.exit(1);
});
